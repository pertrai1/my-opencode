import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import test from "node:test";
import yaml from "js-yaml";
import prompt from "../evals/learn/prompt.js";

const repository = fileURLToPath(new URL("../", import.meta.url));
const directory = join(repository, "evals/learn");
const read = (name) => readFileSync(join(directory, name), "utf8");
const cases = yaml.load(read("examples.yaml"));
const sample = cases.find(({ vars }) => vars.category === "verified");
assert.ok(sample, "Expected a verified-retention case");

function runCli(t, overrides) {
  const temporary = mkdtempSync(join(tmpdir(), "learn-promptfoo-"));
  t.after(() => rmSync(temporary, { recursive: true, force: true }));
  const config = join(temporary, "config.yaml");
  const report = join(temporary, "report.json");
  const capture = join(temporary, "requests.jsonl");
  writeFileSync(config, yaml.dump({
    ...yaml.load(read("promptfooconfig.yaml")), basePath: directory, ...overrides,
  }));
  const result = spawnSync(process.execPath, [
    "--require", join(repository, "evals/failure-reporting/offline.js"),
    join(repository, "node_modules/promptfoo/dist/src/entrypoint.js"),
    "eval", "-c", config, "--no-cache", "--no-write", "--no-share",
    "--no-progress-bar", "--no-table", "-o", report,
  ], {
    cwd: repository, encoding: "utf8", timeout: 60_000,
    env: {
      ...process.env,
      PROMPTFOO_CONFIG_DIR: join(temporary, "state"),
      PROMPTFOO_DISABLE_TELEMETRY: "1", PROMPTFOO_DISABLE_UPDATE: "1",
      PROMPTFOO_CAPTURE_LOG: capture, PROMPTFOO_REQUEST_BACKOFF_MS: "1",
      OPENAI_API_KEY: "SYNTHETIC_OFFLINE_TEST_KEY",
    },
  });
  // Every invocation below deliberately contains failures or provider errors.
  assert.equal(result.status, 100, result.stdout + result.stderr);
  return {
    ...JSON.parse(readFileSync(report, "utf8")).results,
    calls: existsSync(capture) ? readFileSync(capture, "utf8").trim().split("\n").map(JSON.parse) : [],
  };
}

test("live config and npm entry point use real command instructions without answer leakage", () => {
  const config = yaml.load(read("promptfooconfig.yaml"));
  assert.equal(config.providers[0].id, "openai:chat:gpt-4o");
  assert.deepEqual(config.prompts, ["file://prompt.js"]);
  assert.equal(config.tests, "file://examples.yaml");
  const scripts = JSON.parse(readFileSync(join(repository, "package.json"), "utf8")).scripts;
  assert.match(scripts["eval:learn"], /promptfoo eval -c evals\/learn\/promptfooconfig\.yaml/);
  const messages = prompt({ vars: { ...sample.vars, expected: "DO_NOT_SEND_LABELS", semantic_review: "DO_NOT_SEND_NOTES" } });
  const command = readFileSync(join(repository, "commands/learn.md"), "utf8")
    .replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "").replace(/\s*\$ARGUMENTS\s*$/, "").trim();
  const [system = {}] = messages;
  assert.equal(system.content, command);
  assert.doesNotMatch(JSON.stringify(messages), /DO_NOT_SEND_/);
});

test("actual CLI renders all cases and rejects existing capture stub outputs", (t) => {
  const result = runCli(t, {
    providers: [`file://${join(repository, "tests/fixtures/promptfoo-wiring-provider.js")}`],
  });
  assert.equal(result.stats.errors, 0);
  assert.equal(result.stats.failures, 10);
  assert.equal(result.calls.length, 10);
  for (const entry of cases) {
    const call = result.calls.find(({ vars }) => vars.id === entry.vars.id);
    assert.ok(call, entry.description);
    assert.deepEqual(JSON.parse(call.prompt), prompt({ vars: entry.vars }));
    assert.doesNotMatch(call.prompt, /"expected"|"semantic_review"|file:\/\/|\{\{/);
  }
  assert.ok(result.results.every(row => !row.success && !row.gradingResult.pass));
});

test("offline echo calibration accepts hand-authored labels and rejects inverted decisions", (t) => {
  // Calibration only: these candidates are NOT generated by the model or command.
  const tests = cases.flatMap(entry => [true, false].map(correct => ({
    ...entry, description: `${entry.description} calibration-${correct ? "pass" : "fail"}`,
    vars: {
      ...entry.vars,
      offline_candidate: JSON.stringify({
        ...entry.vars.expected,
        decision: correct ? entry.vars.expected.decision : entry.vars.expected.decision === "skip" ? "retain" : "skip",
      }),
    },
  })));
  for (const candidate of [
    { ...sample.vars.expected, learning: "one\ntwo\nthree\nfour" },
    { ...sample.vars.expected, reason: "[SYNTHETIC_PRIVATE_VALUE]" },
    { ...sample.vars.expected, target: "AGENTS.md" },
  ]) tests.push({
    ...sample, description: `invalid-content-${tests.length} calibration-fail`,
    vars: { ...sample.vars, offline_candidate: JSON.stringify(candidate) },
  });
  const result = runCli(t, { prompts: ["{{offline_candidate}}"], providers: ["echo"], tests });
  assert.equal(result.stats.errors, 0);
  assert.equal(result.stats.successes, 10);
  assert.equal(result.stats.failures, 13);
  for (const row of result.results) {
    assert.equal(row.success, row.testCase.description.endsWith("calibration-pass"));
  }
});

test("network-blocked real provider reports an error rather than a passing decision", (t) => {
  const result = runCli(t, { tests: [sample] });
  assert.equal(result.stats.errors, 1);
  assert.equal(result.stats.successes, 0);
  assert.match(result.results[0].error, /disabled for offline calibration/);
});
